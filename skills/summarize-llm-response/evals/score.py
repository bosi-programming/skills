#!/usr/bin/env python3
"""Deterministic scorer for summarize-llm-response runs.

Reads runs/<model>/<case>/<condition>/trial<N>/output.md and checks each
case against the rules SKILL.md actually states. Prints a per-assertion
with/without table and writes score.json next to the runs.
"""
import argparse
import json
import re
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent

FILLER = [
    "here's a summary", "here is a summary", "i hope this helps",
    "hope this helps", "let me know if", "great question",
    "i've gone ahead", "hey team", "hope you're all well",
]
OPENERS = ("hey team", "hi team", "hello", "hey all", "good morning", "good afternoon")
TAG_FULL = re.compile(r"\[Text Generated by AI\s*-\s*[\w.\-]+\]", re.I)
TAG_SECTION = re.compile(r"\[Section updated by AI\s*-\s*[\w.\-]+\]", re.I)
BULLET = re.compile(r"^\s*[-*+]\s+")
CHECKBOX = re.compile(r"^\s*[-*+]\s+\[\s?\]\s+")
NUMBERED = re.compile(r"^\s*\d+[.)]\s+")
TLDR = re.compile(r"tl;?dr", re.I)
MD_BOLD = re.compile(r"\*\*[^*\n]+\*\*")
MRKDWN_BOLD = re.compile(r"(?<!\*)\*[^*\n]+\*(?!\*)")


def lines(text):
    return [l for l in text.splitlines()]


def content_lines(text):
    return [l.strip() for l in text.splitlines() if l.strip()]


def strip_code_blocks(text):
    return re.sub(r"```.*?```", "", text, flags=re.S)


def sentences(text):
    return [s for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s]


def word_count(line):
    stripped = re.sub(r"^\s*(?:[-*+]\s+(?:\[[ x]\]\s+)?|\d+[.)]\s+|#+\s+|>\s?)", "", line)
    return len(stripped.split())


def index_of(pred, ls, last=False):
    hits = [i for i, l in enumerate(ls) if pred(l)]
    if not hits:
        return None
    return hits[-1] if last else hits[0]


TITLE_LINE = re.compile(r"^[*_\s]*(?:task\s+|issue\s+|page\s+)?title[*_\s]*:\s*", re.I)
PREAMBLE = re.compile(
    r"^(here'?s?\b|here is\b|sure\b|based on\b|since no\b|i'?ll\b|i have\b|below\b|"
    r"this is (?:the|a)\b|the following\b|okay\b|got it\b|no \w+ integration\b|"
    r"without (?:a|an|the)? ?\w+ integration\b|two notes\b|note:)", re.I,
)


def find_title_line(ls):
    for l in ls:
        if TITLE_LINE.match(l):
            return TITLE_LINE.sub("", l).strip().strip("*`_ ")
    return None


def has_preamble(ls):
    return bool(ls) and bool(PREAMBLE.match(ls[0]))


def universal(text):
    """Rules SKILL.md applies to every output. Line budget: 20 words per line."""
    body = strip_code_blocks(text)
    low = body.lower()
    ls = content_lines(body)
    over = [l for l in ls if word_count(l) > 20]
    return {
        "no_filler_phrases": (not any(f in low for f in FILLER), None),
        "within_line_budget": (
            not over,
            f"{len(over)}/{max(len(ls), 1)} lines over budget"
            + (f" | worst: {max((word_count(l) for l in over), default=0)}w" if over else ""),
        ),
    }


def case1(text):
    ls = content_lines(text)
    tl = index_of(lambda l: TLDR.search(l), ls)
    last_item = index_of(lambda l: BULLET.match(l) or NUMBERED.match(l), ls, last=True)
    return {
        "tldr_present": (tl is not None, None),
        "tldr_is_last_section": (
            tl is not None and last_item is not None and tl > last_item,
            f"tldr@{tl} last_item@{last_item}",
        ),
        "findings_as_bullets": (sum(1 for l in ls if BULLET.match(l)) >= 3, None),
        "inline_code_ref": ("PaymentService.ts:142" in text, None),
        "numbered_next_steps": (sum(1 for l in ls if NUMBERED.match(l)) >= 2, None),
        "no_preamble": (not has_preamble(ls), ls[0][:50] if ls else ""),
        "no_attribution_tag": (not TAG_FULL.search(text), None),
        "no_title_field": (find_title_line(ls) is None, find_title_line(ls)),
    }


def content_only(text):
    """The draft must be postable as-is: no wrapper, no meta-commentary."""
    ls = content_lines(text)
    return (not has_preamble(ls), ls[0][:60] if ls else "")


def case2(text):
    ls = content_lines(text)
    title = find_title_line(ls)
    tag = index_of(lambda l: TAG_FULL.search(l), ls)
    first_bullet = index_of(lambda l: BULLET.match(l), ls)
    return {
        "title_has_category_prefix": (
            bool(title) and bool(re.match(r"^\[[^\]]+\]", title)), title,
        ),
        "title_max_10_words": (bool(title) and len(title.split()) <= 10, title),
        "attribution_tag_present": (tag is not None, None),
        "tag_before_body_content": (
            tag is not None and (first_bullet is None or tag < first_bullet), None,
        ),
        "title_has_no_tag": (bool(title) and not TAG_FULL.search(title), None),
        "action_items_as_checklist": (sum(1 for l in ls if CHECKBOX.match(l)) >= 2, None),
        "detail_bullets_present": (sum(1 for l in ls if BULLET.match(l)) >= 3, None),
        "content_only_no_wrapper": content_only(text),
    }


def case3(text):
    ls = content_lines(text)
    return {
        "prose_not_bullets": (sum(1 for l in ls if BULLET.match(l)) == 0, None),
        "no_tldr_header": (not TLDR.search(text), None),
        "max_3_sentences": (len(sentences(strip_code_blocks(text))) <= 3, f"{len(sentences(strip_code_blocks(text)))} sentences"),
        "no_preamble": (not has_preamble(ls), ls[0][:50] if ls else ""),
    }


def case4(text):
    ls = content_lines(text)
    return {
        "section_update_tag_used": (bool(TAG_SECTION.search(text)), None),
        "no_full_generation_tag": (not TAG_FULL.search(text), None),
        "converted_to_bullets": (sum(1 for l in ls if BULLET.match(l)) >= 2, None),
        "filler_removed": (
            "make sure everything is tested properly" not in text.lower(), None,
        ),
        "content_only_no_wrapper": content_only(text),
    }


def case5(text):
    body = strip_code_blocks(text)
    ls = content_lines(body)
    return {
        "no_markdown_bold": (not MD_BOLD.search(body), None),
        "uses_mrkdwn_bold": (bool(MRKDWN_BOLD.search(body)), None),
        "states_deploy_time": (bool(re.search(r"10\s*(?::00)?\s*pm", body, re.I)), None),
        "states_maintenance_window": (
            bool(re.search(r"\b2[\s-]*(?:min|minute)", body, re.I)), None,
        ),
        "names_affected_system": (
            bool(re.search(r"webhook|v2", body, re.I)), None,
        ),
        "no_attribution_tag": (not TAG_FULL.search(body), None),
        "no_filler_opener": (
            bool(ls)
            and not ls[0].lower().lstrip(":*_ ").startswith(OPENERS)
            and not has_preamble(ls),
            ls[0][:50] if ls else "",
        ),
    }


def case6(text):
    ls = content_lines(text)
    title = find_title_line(ls)
    tag = index_of(lambda l: TAG_FULL.search(l), ls)
    return {
        "title_max_8_words": (bool(title) and len(title.split()) <= 8, title),
        "title_verb_first": (
            bool(title) and title.split()[0].lower() in {
                "add", "fix", "check", "update", "remove", "write", "guard",
                "patch", "implement", "handle", "prevent", "create",
            }, title,
        ),
        "title_has_no_tag": (bool(title) and not TAG_FULL.search(title), None),
        "description_has_attribution": (tag is not None, None),
        "description_1_to_3_bullets": (
            1 <= sum(1 for l in ls if BULLET.match(l)) <= 3,
            f"{sum(1 for l in ls if BULLET.match(l))} bullets",
        ),
        "content_only_no_wrapper": content_only(text),
    }


SKIP_NARRATION = re.compile(
    r"(skip|not applying|does not apply|doesn't apply|bail|per the .*skill|"
    r"summarize-llm-response)", re.I,
)


def bailout(text):
    """Skip-list cases: the skill must stand down and not say that it did."""
    ls = content_lines(text)
    return {
        "no_tldr": (not TLDR.search(text), None),
        "no_attribution_tag": (not TAG_FULL.search(text) and not TAG_SECTION.search(text), None),
        "no_checklist": (sum(1 for l in ls if CHECKBOX.match(l)) == 0, None),
        "no_skip_narration": (not SKIP_NARRATION.search(text), None),
    }


def case7(text):
    return bailout(text)


def case8(text):
    out = bailout(text)
    out.pop("no_checklist", None)
    out["has_code_block"] = ("```" in text, None)
    return out


CHECKS = {1: case1, 2: case2, 3: case3, 4: case4, 5: case5, 6: case6, 7: case7, 8: case8}


NO_UNIVERSAL = {7, 8}


def score_output(case_id, text):
    result = {} if case_id in NO_UNIVERSAL else dict(universal(text))
    result.update(CHECKS[case_id](text))
    return result


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="claude-sonnet-5")
    args = ap.parse_args()

    root = EVAL_DIR / "runs" / args.model.replace("/", "__")
    if not root.exists():
        raise SystemExit(f"no runs at {root}")

    report = {}
    for case_dir in sorted(root.iterdir(), key=lambda p: int(p.name) if p.name.isdigit() else 0):
        if not case_dir.is_dir():
            continue
        cid = int(case_dir.name)
        report[cid] = {}
        for cond_dir in sorted(case_dir.iterdir()):
            outs = sorted(cond_dir.glob("trial*/output.md"))
            if not outs:
                continue
            per_trial = [score_output(cid, o.read_text()) for o in outs]
            merged = {}
            for name in per_trial[0]:
                passes = sum(1 for t in per_trial if t[name][0])
                merged[name] = {
                    "passed": passes,
                    "total": len(per_trial),
                    "detail": per_trial[0][name][1],
                }
            report[cid][cond_dir.name] = merged

    (root / "score.json").write_text(json.dumps(report, indent=2))

    for cid, conds in report.items():
        print(f"\n=== case {cid} ===")
        names = sorted({n for c in conds.values() for n in c})
        w = max(len(n) for n in names) + 2
        print(f"{'assertion'.ljust(w)}{'with':>8}{'without':>10}   detail")
        for n in names:
            wv = conds.get("with", {}).get(n)
            ov = conds.get("without", {}).get(n)
            fmt = lambda v: f"{v['passed']}/{v['total']}" if v else "-"
            det = (wv or ov or {}).get("detail") or ""
            print(f"{n.ljust(w)}{fmt(wv):>8}{fmt(ov):>10}   {det}")

    tot_w = sum(v["passed"] for c in report.values() for v in c.get("with", {}).values())
    den_w = sum(v["total"] for c in report.values() for v in c.get("with", {}).values())
    tot_o = sum(v["passed"] for c in report.values() for v in c.get("without", {}).values())
    den_o = sum(v["total"] for c in report.values() for v in c.get("without", {}).values())
    print(f"\nTOTAL  with {tot_w}/{den_w}   without {tot_o}/{den_o}")
    print(f"score.json: {root / 'score.json'}")


if __name__ == "__main__":
    main()
